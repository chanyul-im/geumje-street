export function matchup(attack: PType, defend: PType): number {
  return CHART[attack][defend] ?? 1;
}

export function effectiveness(attack: PType, defend: readonly PType[]): number {
  return defend.reduce((mult, type) => mult * matchup(attack, type), 1);
}

export function effectText(mult: number): string | null {
  if (mult === 0) return "효과가 없는 것 같다…";
  if (mult < 1) return "효과가 별로인 듯하다";
  if (mult > 1) return "효과가 굉장했다!";
  return null;
}
